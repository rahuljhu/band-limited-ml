"""Paper 7 results: tables, figure and numbers from results/p7_beads (thinning sweep on beads 0, 1, 3; all isolated beads
at full counts with summary.json from p7_beads_summary.py and p7_beads_plane.py) and results/p7_lines.
Writes papers/paper7/tables/{beads_n,lines}.tex, figs/beads_edge.pdf, numbers_results.tex."""
import json, glob, numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
PP = 'papers/paper7'; num = {}
f4 = lambda v: f'{v:+.4f}'; big = lambda v: f'{int(v):,}'.replace(',', '{,}')
# thinning sweep
rows = []
for b, lab in ((0, 'A'), (1, 'B'), (3, 'C')):
    for n in ('1000', '3000', '10000', '30000', '100000', 'full'):
        r = json.load(open(f'results/p7_beads/b{b}_{n}_0.json')); d = r['emp_minus_ml']
        if n != 'full' and r['n'] >= json.load(open(f'results/p7_beads/b{b}_full_0.json'))['n']:
            continue                                     # thinning target above the bead's own counts
        rows.append(f"{b} & {r['per_pixel']:.1f} & {r['ml']['test']:.4f} & {r['empirical']['test']:.4f} & {d['mean']:+.4f} ({d['se']:.4f}) & "
                    f"{r['kde']['test']:.4f} & {r['histogram']['test']:.4f} & {r['empirical']['lam']:g} \\\\")
        if n == '1000':
            num[f'Low{lab}'] = f4(d['mean']); num[f'LowSE{lab}'] = f"{d['se']:.4f}"; num[f'LowPx{lab}'] = f"{r['per_pixel']:.1f}"
        if n == 'full':
            num[f'Full{lab}'] = f4(d['mean']); num[f'FullSE{lab}'] = f"{d['se']:.4f}"
    rows[-1] += '\n\\midrule' if b != 3 else ''
open(f'{PP}/tables/beads_n.tex', 'w').write(
    '\\begin{tabular}{rrrrrrrr}\n\\toprule\nbead & photons/px & ML & empirical & emp.\\ $-$ ML & KDE & histogram & $\\lambda$ \\\\\n\\midrule\n'
    + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n')
# all beads
S = json.load(open('results/p7_beads/summary.json')); R = S['rows']
e = np.array([x['edge'] for x in R]); d = np.array([x['d'] for x in R]); se = np.array([x['se'] for x in R])
pl = np.array([x['empirical'] - x['emp_plane'] for x in R])
num.update(NBeads=S['n'], Wins=S['wins'], Losses=S['losses'], Ties=S['ties'], MedD=f4(S['median_d']), Rho=f"{S['spearman']:.2f}",
           MedEdge=f"{100 * S['median_edge']:.1f}", MedDLow=f4(S['median_d_low_edge']), MedDHigh=f4(S['median_d_high_edge']),
           KdeBeatsMl=S['kde_beats_ml'], EmpBeatsKde=S['emp_beats_kde'], LamEdge=S['lam_edge'], PxLo=f"{S['per_px'][0]:.0f}",
           PxHi=f"{S['per_px'][1]:.0f}", PlaneMax=f"{np.abs(pl).max():.0e}".replace('e-0', 'e-'),
           MlNyq=sum(0.5 in json.load(open(f"results/p7_beads/b{x['bead']}_full_0.json"))['ml']['fc'] for x in R),
           HistBeatsMl=sum(x['histogram'] > x['ml'] for x in R))
fig, ax = plt.subplots(figsize=(4.6, 3.2))
ax.errorbar(100 * e, d, yerr=se, fmt='o', ms=3.5, lw=0.8, color='C0'); ax.axhline(0, color='k', lw=0.6)
ax.set_xscale('log'); ax.set_xlabel('counts on the window edge (%)'); ax.set_ylabel('empirical $-$ ML (nats / photon)')
fig.tight_layout(); fig.savefig(f'{PP}/figs/beads_edge.pdf'); fig.savefig(f'{PP}/figs/beads_edge.png', dpi=150)
# lines
LAB = dict(photon='photons, single mode', electron='electrons', photon_mm='photons, multimode'); lr = []
for name, t in (('photon', 'Sm'), ('electron', 'El'), ('photon_mm', 'Mm')):
    r = json.load(open(f'results/p7_lines/{name}.json')); dd = r['emp_minus_ml']
    lr.append(f"{LAB[name]} & {r['per_bin']:.1f} & {r['ml']['test']:.4f} & {r['empirical']['test']:.4f} & {dd['mean']:+.4f} ({dd['se']:.4f}) & "
              f"{r['ml']['fc']:.3f} & {r['empirical']['fc']:.3f} & {r['empirical']['lam']:g} \\\\")
    num.update({f'Line{t}': f4(dd['mean']), f'Line{t}SE': f"{dd['se']:.4f}", f'Line{t}Bin': f"{r['per_bin']:.0f}"})
open(f'{PP}/tables/lines.tex', 'w').write(
    '\\begin{tabular}{lrrrrrrr}\n\\toprule\n& & & & & \\multicolumn{2}{c}{$f_c$} & \\\\\n\\cmidrule(lr){6-7}\n'
    'record & counts/bin & ML & empirical & emp.\\ $-$ ML & ML & emp. & $\\lambda$ \\\\\n\\midrule\n' + '\n'.join(lr) + '\n\\bottomrule\n\\end{tabular}\n')
open(f'{PP}/numbers_results.tex', 'w').write('% generated by results/p7_paper.py\n' + ''.join(f'\\newcommand{{\\P{k}}}{{{v}}}\n' for k, v in num.items()))
print(num)
# streaming (results/p7_stream.py: burn-in 2000 / batches 400, and _burn5000: 5000 / 2000)
sr = []
for name, t in (('photon', 'Sm'), ('electron', 'El'), ('photon_mm', 'Mm')):
    for tag, bt_ in (('_burn5000', 'A'), ('', 'B')):
        r = json.load(open(f'results/p7_stream/{name}{tag}.json')); s, o, dd = r['stream'], r['oneshot'], r['stream_minus_oneshot']
        sr.append(f"{LAB[name] if tag == '_burn5000' else ''} & {big(r['burn'])} / {big(r['nb'])} & {o['fc']:.3f} & {o['lam']:g} & {s['fc_burn']:.3f} & {s['lam']:g} & "
                  f"{s['fc']:.3f} & {s['epochs']} & {dd['mean']:+.4f} ({dd['se']:.4f}) \\\\".replace('(0.0000)', '($<$0.0001)'))
        num.update({f'St{t}{bt_}': f4(dd['mean']), f'St{t}{bt_}SE': f"{dd['se']:.4f}", f'St{t}{bt_}Fc': f"{s['fc']:.3f}",
                    f'St{t}{bt_}FcB': f"{s['fc_burn']:.3f}", f'St{t}{bt_}N': big(r['n_stream'])})
    num[f'St{t}FcO'] = f"{o['fc']:.3f}"
    sr[-1] += '\n\\midrule' if name != 'photon_mm' else ''
open(f'{PP}/tables/stream.tex', 'w').write(
    '\\begin{tabular}{lrrrrrrrr}\n\\toprule\n& & \\multicolumn{2}{c}{one-shot} & \\multicolumn{2}{c}{burn-in} & \\multicolumn{2}{c}{stream} & \\\\\n'
    '\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\n'
    'record & burn-in / batch & $f_c$ & $\\lambda$ & $f_c$ & $\\lambda$ & $f_c$ & epochs & stream $-$ one-shot \\\\\n\\midrule\n' + '\n'.join(sr) + '\n\\bottomrule\n\\end{tabular}\n')
open(f'{PP}/numbers_results.tex', 'w').write('% generated by results/p7_paper.py\n' + ''.join(f'\\newcommand{{\\P{k}}}{{{v}}}\n' for k, v in num.items()))
# against paper 3's estimator (results/p7_beads_ball.py: ball kernel, selector fc up to 1/px, EM floor; paired)
RB = [json.load(open(f)) for f in glob.glob('results/p7_beads/ball_b*.json')]
for l, t in (('real_ball', 'Re'), ('complex_ball', 'Cx')):
    d = np.array([r[l]['emp_minus'] for r in RB]); z = d / np.array([r[l]['se'] for r in RB])
    num.update({f'Ball{t}Wins': int((z > 2).sum()), f'Ball{t}Ties': int((abs(z) <= 2).sum()), f'Ball{t}Losses': int((z < -2).sum()),
                f'Ball{t}Med': f4(np.median(d)), f'Ball{t}FcMed': f"{np.median([np.ravel(r[l]['fc'])[0] for r in RB]):.2f}"})
num['BallFcAbove'] = int(sum(np.ravel(r['real_ball']['fc'])[0] > 0.5 for r in RB))
open(f'{PP}/numbers_results.tex', 'w').write('% generated by results/p7_paper.py\n' + ''.join(f'\\newcommand{{\\P{k}}}{{{v}}}\n' for k, v in num.items()))

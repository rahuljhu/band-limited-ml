"""Paper 5 figures 1-2 and their numbers from results/p5synth (p5_synth_figs.py).
  Fig 1 (fixed): streaming at a frozen cut-off to tol against BCD at the same cut-off and tol (CPU).
  Fig 2 (select): streaming with Adam on fc against one-shot selection + refit (GPU, else CPU).
Each figure: time (left) and relative ISE (right) against n, one colour per truth, medians over replicates with
min-max bars. Writes papers/paper2/figs/{fixed,select}.pdf and papers/paper2/numbers_synth.tex."""
import os, sys, json, glob
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

R = os.path.dirname(os.path.abspath(__file__))
P = os.path.join(R, '..', 'papers', 'paper2')
COL = {'T1': 'C0', 'T2': 'C1', 'T3': 'C2'}
PARTS = {'fixed': (('bcd_fixed', 'BCD', '--', 's'), ('stream_fixed', 'streaming', '-', 'o')),
         'select': (('oneshot_select', 'one-shot selection', '--', 's'), ('stream_adam', 'streaming (Adam)', '-', 'o'))}


def load(part):
    out = {}
    for eng in ('gpu', 'cpu') if part == 'select' else ('cpu', 'gpu'):
        for p in sorted(glob.glob(os.path.join(R, 'p5synth', f'{part}_*_{eng}.json'))):
            j = json.load(open(p))
            out.setdefault(eng, {})[(j['truth'], j['n'])] = j
        if eng in out:
            return eng, out[eng]
    return None, {}


def fig(part, eng, D):
    fig, ax = plt.subplots(1, 2, figsize=(9, 3.4))
    truths = sorted({k[0] for k in D})
    for kind in truths:
        ns = sorted(n for (t, n) in D if t == kind)
        for key, lab, ls, mk in PARTS[part]:
            for a, f in ((ax[0], 's'), (ax[1], 'rel_ise')):
                v = [[r[key][f] for r in D[(kind, n)]['reps']] for n in ns]
                med = [np.median(x) for x in v]
                err = [[m - min(x) for m, x in zip(med, v)], [max(x) - m for m, x in zip(med, v)]]
                a.errorbar(ns, med, yerr=err, color=COL[kind], ls=ls, marker=mk, capsize=3,
                           label=f'{kind}, {lab}')
    for a, yl in ((ax[0], 'time (s)'), (ax[1], 'relative ISE')):
        a.set_xscale('log'); a.set_yscale('log'); a.set_xlabel('$n$'); a.set_ylabel(yl)
        a.set_xticks(sorted({k[1] for k in D})); a.get_xaxis().set_major_formatter(matplotlib.ticker.ScalarFormatter())
        a.minorticks_off()
    ax[0].legend(fontsize=7, ncol=1)
    fig.tight_layout(); fig.savefig(os.path.join(P, 'figs', f'{part}.pdf')); plt.close(fig)


def ratios(D, a, b, f):
    """Per-cell median over replicates of a[f]/b[f], paired by replicate."""
    return {k: float(np.median([r[a][f] / r[b][f] for r in j['reps']])) for k, j in D.items()}


def rng(d):
    v = list(d.values())
    return f'{min(v):.3g}--{max(v):.3g}' if v else '?'


if __name__ == '__main__':
    lines = ['% generated by results/make_paper5_figs.py']
    for part, (a, b) in (('fixed', ('stream_fixed', 'bcd_fixed')), ('select', ('stream_adam', 'oneshot_select'))):
        eng, D = load(part)
        if not D:
            print(part, 'no data'); tag = part.capitalize()
            lines += [f'\\newcommand{{\\{tag}{m}}}{{\\cc{{pending}}}}' for m in
                      ('Engine', 'SpeedRange', 'IseRatioRange', 'SpeedTwentyK', 'IseTwentyK', 'SpeedFiftyK', 'IseFiftyK')]
            continue
        fig(part, eng, D)
        tr = ratios(D, a, b, 's') if part == 'fixed' else ratios(D, b, a, 's')   # fixed: stream/BCD time; select: one-shot/stream
        er = ratios(D, a, b, 'rel_ise')
        tag = part.capitalize()
        lines += [f'\\newcommand{{\\{tag}Engine}}{{{eng.upper()}}}',
                  f'\\newcommand{{\\{tag}SpeedRange}}{{{rng(tr)}}}',
                  f'\\newcommand{{\\{tag}IseRatioRange}}{{{rng(er)}}}']
        for n in sorted({k[1] for k in D}):
            sub = {k: v for k, v in tr.items() if k[1] == n}
            esub = {k: v for k, v in er.items() if k[1] == n}
            nn = {20000: 'TwentyK', 50000: 'FiftyK'}.get(n, f'N{n}')
            lines += [f'\\newcommand{{\\{tag}Speed{nn}}}{{{rng(sub)}}}', f'\\newcommand{{\\{tag}Ise{nn}}}{{{rng(esub)}}}']
        if part == 'fixed':
            nc = sum(not r['stream_fixed'].get('converged', True) for j in D.values() for r in j['reps'])
            lines += [f'\\newcommand{{\\FixedNotConverged}}{{{nc}}}',
                      f'\\newcommand{{\\FixedReps}}{{{sum(len(j["reps"]) for j in D.values())}}}']
            ep = [r['stream_fixed']['epochs'] for j in D.values() for r in j['reps'] if r['stream_fixed'].get('epochs')]
            sw = [r['bcd_fixed']['sweeps'] for j in D.values() for r in j['reps'] if r['bcd_fixed'].get('sweeps')]
            lines += [f'\\newcommand{{\\FixedEpochs}}{{{min(ep)}--{max(ep)}}}', f'\\newcommand{{\\FixedSweeps}}{{{min(sw)}--{max(sw)}}}']
        for k in sorted(D):
            print(part, eng, k, f'speed(b/a) {tr[k]:.2f}  ise(a/b) {er[k]:.2f}')
    open(os.path.join(P, 'numbers_synth.tex'), 'w').write('\n'.join(lines) + '\n')

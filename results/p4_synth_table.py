"""Paper 4: table and numbers from results/p4_synth (three seeds per cell). -> papers/paper4/tables/synth.tex, numbers.tex"""
import json, glob, numpy as np
R = [json.load(open(f)) for f in glob.glob('results/p4_synth/n*_*.json')]; rows, num = [], {}
cell = lambda n, s, g: [x for r in R if r['n'] == n for x in r['rows'] if x['s'] == s and x['gamma'] == g]
for s in (2.0, 4.0):
    for g in (0.0, 0.5, 0.9, 1.0):
        line = f"{s:g} & {g:g} & {cell(10 ** 6, s, g)[0]['true_spectrum'][1]:.3f}"
        for n in (10 ** 4, 10 ** 5, 10 ** 6):
            X = cell(n, s, g); k1, k2 = (1e3 * np.mean([x[f'K{K}']['kl'] for x in X]) for K in (1, 2))
            line += f" & {k1:.2f} & {k2:.2f} & {sum(x['val_pick'] == 2 for x in X)}/{len(X)}"
        X = cell(10 ** 6, s, g); line += f" & {np.mean([x['K2']['spectrum'][1] for x in X]):.3f} \\\\"
        rows.append(line)
    rows[-1] += '\n\\midrule' if s == 2.0 else ''
open('papers/paper4/tables/synth.tex', 'w').write(
    '\\begin{tabular}{rrr' + 'rrr' * 3 + 'r}\n\\toprule\n& & & \\multicolumn{3}{c}{$n=10^4$} & \\multicolumn{3}{c}{$n=10^5$} & \\multicolumn{3}{c}{$n=10^6$} & \\\\\n'
    '\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-12}\n'
    '$s$ & $\\gamma$ & $\\lambda_2$ & $K{=}1$ & $K{=}2$ & picks 2 & $K{=}1$ & $K{=}2$ & picks 2 & $K{=}1$ & $K{=}2$ & picks 2 & $\\hat\\lambda_2$ \\\\\n\\midrule\n'
    + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n')
inc = [x for n in (10 ** 5, 10 ** 6) for s in (2.0, 4.0) for g in (0.0, 0.5, 0.9) for x in cell(n, s, g)]
coh = [x for n in (10 ** 5, 10 ** 6) for s in (2.0, 4.0) for x in cell(n, s, 1.0)]
num = dict(IncPick=f"{sum(x['val_pick'] == 2 for x in inc)}", IncN=len(inc), CohPick=f"{sum(x['val_pick'] == 1 for x in coh)}", CohN=len(coh),
           KlOneMax=f"{1e3 * max(np.mean([x['K1']['kl'] for x in cell(10 ** 6, s, 0.0)]) for s in (2.0, 4.0)):.0f}",
           KlTwoMax=f"{1e3 * max(np.mean([x['K2']['kl'] for x in cell(10 ** 6, s, g)]) for s in (2.0, 4.0) for g in (0.0, 0.5, 0.9, 1.0)):.2f}",
           SpecMax=f"{max(np.mean([x['K2']['spectrum'][1] for x in cell(10 ** 6, s, 0.0)]) for s in (2.0, 4.0)):.2f}",
           SpecMin=f"{min(np.mean([x['K2']['spectrum'][1] for x in cell(10 ** 6, s, 0.0)]) for s in (2.0, 4.0)):.2f}")
open('papers/paper4/numbers.tex', 'w').write('% generated by results/p4_synth_table.py\n' + ''.join(f'\\newcommand{{\\S{k}}}{{{v}}}\n' for k, v in num.items()))
print(num)

"""Paper 2, real data: table and numbers from results/stream_real (results/stream_real.py; the paper's CPU protocol,
and the small burn-in runs tagged _burn2000). Fringe axis: photons 0 (rows), electrons 1 (columns); physical band of the
density along it from paper 3's Fraunhofer fits (results/dslit_1d/table.json).
Writes papers/paper2/tables/real.tex and papers/paper2/numbers_real.tex."""
import json
R0, PP = 'results/stream_real', 'papers/paper2'
SETS = [('photon_mm', 'photons, multimode', 0, 'Mm'), ('photon', 'photons, single mode', 0, 'Sm'), ('electron', 'electrons', 1, 'El')]
phys = {k: v['phys'] for k, v in json.load(open('results/dslit_1d/table.json')).items()}
big = lambda v: f'{int(v):,}'.replace(',', '{,}')
num, rows = {}, []
for name, lab, ax, t in SETS:
    r = json.load(open(f'{R0}/{name}.json'))
    rows.append(f"{lab} & {big(r['n_train'])} & {r['stream_s']:.0f} & {r['oneshot_s']:.0f} & {r['speedup']:.1f} & "
                f"{r['diff']:+.4f} ({r['diff_se']:.4f}) & {r['stream_fc'][ax] / phys[name]:.2f} & {r['oneshot_fc'][ax] / phys[name]:.2f} \\\\")
    num.update({f'{t}N': big(r['n_train']), f'{t}Speed': f"{r['speedup']:.1f}", f'{t}StreamS': f"{r['stream_s']:.0f}",
                f'{t}OneS': f"{r['oneshot_s']:.0f}", f'{t}D': f"{r['diff']:+.4f}", f'{t}SE': f"{r['diff_se']:.4f}",
                f'{t}FcS': f"{r['stream_fc'][ax] / phys[name]:.2f}", f'{t}FcO': f"{r['oneshot_fc'][ax] / phys[name]:.2f}",
                f'{t}FcAcrossS': f"{r['stream_fc'][1 - ax]:.3f}", f'{t}FcAcrossO': f"{r['oneshot_fc'][1 - ax]:.3f}"})
    if name != 'photon_mm':
        b = json.load(open(f'{R0}/{name}_burn2000.json'))
        num.update({f'{t}BD': f"{b['diff']:+.4f}", f'{t}BSE': f"{b['diff_se']:.4f}", f'{t}BFcS': f"{b['stream_fc'][ax] / phys[name]:.2f}"})
with open(f'{PP}/tables/real.tex', 'w') as f:
    f.write('\\begin{tabular}{lrrrrrrr}\n\\toprule\n& & \\multicolumn{3}{c}{time (s)} & & \\multicolumn{2}{c}{$f_c$ / band} \\\\\n'
            '\\cmidrule(lr){3-5}\\cmidrule(lr){7-8}\n'
            'record & $n$ & stream & one-shot & ratio & stream $-$ one-shot & stream & one-shot \\\\\n\\midrule\n'
            + '\n'.join(rows) + '\n\\bottomrule\n\\end{tabular}\n')
open(f'{PP}/numbers_real.tex', 'w').write('% generated by results/stream_real_table.py\n' + ''.join(f'\\newcommand{{\\Real{k}}}{{{v}}}\n' for k, v in num.items()))
print(num)
